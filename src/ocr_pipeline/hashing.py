"""File hashing (used to detect that a raw PDF changed between runs)."""
from __future__ import annotations

import hashlib


def sha256_file(path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(chunk)
            if not b:
                break
            h.update(b)
    return h.hexdigest()
